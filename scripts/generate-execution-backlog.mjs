function taskFor(phaseIndex, localIndex) {
  const phase = phases[phaseIndex];
  const area = phase.areas[localIndex % phase.areas.length];
  const verb = verbs[Math.floor(localIndex / phase.areas.length) % verbs.length];
  const criterion = criteria[(phaseIndex + localIndex) % criteria.length];
  const execution = phaseIndex === 6 && [1, 2, 3, 4, 5].includes(localIndex % 10)
    ? "مشروط: لا ينفذ إلا إذا كانت صحة OpenCode والنموذج المفعّل وسياسة التنفيذ الخادمية متحققة."
    : phaseIndex === 7 && [3, 5].includes(localIndex % 10)
      ? "مشروط: لا يبني Theia أو يفعّل توليد Presenton إلا إذا كفت الموارد وتوفرت تهيئة مشروعة."
      : "محلي قابل للتنفيذ أو التحقق ضمن المستودع الحالي.";
  return { area, verb, criterion, execution };
}

